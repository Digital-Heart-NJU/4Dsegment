import pymeshfix
import pyvista as pv
import numpy as np
import os


def write_unstructured_vtk(filepath: str, points: np.ndarray, faces: np.ndarray,
                           elem_tags: np.ndarray = None, fibers: np.ndarray = None) -> None:
    num_pts = points.shape[0]
    num_cells = faces.shape[0]

    if elem_tags is None:
        elem_tags = np.zeros(num_cells, dtype=int)
    if fibers is None:
        fibers = np.ones((num_cells, 3), dtype=float)
        fibers[:, 1:] = 0.0

    with open(filepath, 'w') as f:
        f.write("# vtk DataFile Version 3.0\nvtk output\nASCII\nDATASET UNSTRUCTURED_GRID\n\n")

        f.write(f"POINTS {num_pts} float\n")
        for pt in points:
            f.write(f"{pt[0]:.5f} {pt[1]:.5f} {pt[2]:.5f}\n")
        f.write("\n")

        f.write(f"CELL_TYPES {num_cells}\n")
        f.write("5\n" * num_cells)
        f.write("\n")

        total_conn = num_cells * 4
        f.write(f"CELLS {num_cells} {total_conn}\n")
        for face in faces:
            f.write(f"3 {face[0]} {face[1]} {face[2]}\n")
        f.write("\n")

        f.write(f"CELL_DATA {num_cells}\n")
        f.write("SCALARS elemTag int 1\nLOOKUP_TABLE default\n")
        for tag in elem_tags:
            f.write(f"{int(tag)}\n")
        f.write("\n")

        f.write("VECTORS fiber float\n")
        for vec in fibers:
            f.write(f"{vec[0]:.5f} {vec[1]:.5f} {vec[2]:.5f}\n")


def mesh_fix(input_vtk, output_dir, output_name="M3_fixed.vtk"):
    final_vtk = os.path.join(output_dir, output_name)

    mesh = pv.read(input_vtk)
    mesh = mesh.extract_surface().triangulate()

    # 👇 关键1：确保数组连续内存，避免底层 C++ 库读取错位
    v = np.ascontiguousarray(mesh.points, dtype=np.float64)

    faces_raw = mesh.faces
    faces_list = []
    i = 0
    while i < len(faces_raw):
        n = faces_raw[i]
        if n == 3:
            faces_list.append(faces_raw[i + 1:i + 4])
        i += n + 1
    f = np.ascontiguousarray(faces_list, dtype=np.int32)

    print(f'[DEBUG] Before repair -> Points: {v.shape[0]}, Faces: {f.shape[0]}')
    print(f'[DEBUG] BBox Before -> X:{v[:, 0].min():.3f}~{v[:, 0].max():.3f}, Y:{v[:, 1].min():.3f}~{v[:, 1].max():.3f}, Z:{v[:, 2].min():.3f}~{v[:, 2].max():.3f}')

    # 👇 修改处：先初始化，再通过属性设置参数
    mf = pymeshfix.MeshFix(v, f)
    mf.repair(verbose=True)
    mf.join_distance = 0.0   # 禁止顶点合并，保留原始坐标
    mf.repair()

    fixed_v = mf.v
    fixed_f = mf.f
    print(f'[DEBUG] After repair  -> Points: {fixed_v.shape[0]}, Faces: {fixed_f.shape[0]}')
    print(
        f'[DEBUG] BBox After  -> X:{fixed_v[:, 0].min():.3f}~{fixed_v[:, 0].max():.3f}, Y:{fixed_v[:, 1].min():.3f}~{fixed_v[:, 1].max():.3f}, Z:{fixed_v[:, 2].min():.3f}~{fixed_v[:, 2].max():.3f}')

    write_unstructured_vtk(final_vtk, fixed_v, fixed_f)
    print(f'[INFO] Saved: {final_vtk}')


